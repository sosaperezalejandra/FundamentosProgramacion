    private void inicializarTablas() {
        
     String columnasVentas[] = {
        "Producto", "Lunes", "Martes", "Miércoles",
        "Jueves", "Viernes", "Sábado", "Domingo"
    };

    DefaultTableModel modeloVentas = new DefaultTableModel(columnasVentas, 0);
    tblVentas.setModel(modeloVentas);

    String columnasPrecios[] = {
        "Producto", "Costo", "Precio Venta"
    };

    DefaultTableModel modeloPrecios = new DefaultTableModel(columnasPrecios, 0);
    tblPrecios.setModel(modeloPrecios);

    // no deja que edite los valores de la tabla 3
    String columnasResultados[] = {
        "Producto", "Ingresos Totales", "Utilidad Total"
    };

    DefaultTableModel modeloResultados = new DefaultTableModel(columnasResultados, 0) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };
    tblResultados.setModel(modeloResultados);

    modeloVentas.addTableModelListener(e -> {

        if (e.getColumn() == 0) {

            int row = e.getFirstRow();
            Object prodObj = modeloVentas.getValueAt(row, 0);

            if (prodObj == null) return;

            String producto = prodObj.toString().trim();
            if (producto.isEmpty()) return;

            for (int i = 0; i < modeloPrecios.getRowCount(); i++) {
                Object p2 = modeloPrecios.getValueAt(i, 0);
                if (p2 != null && p2.toString().equalsIgnoreCase(producto)) {
                    return;
                }
            }
            
            for (int i = 0; i < modeloPrecios.getRowCount(); i++) {
                Object p2 = modeloPrecios.getValueAt(i, 0);
                if (p2 == null || p2.toString().trim().isEmpty()) {
                    modeloPrecios.setValueAt(producto, i, 0);
                    return; // rellenó la fila existente → terminar
                }
            }
            modeloPrecios.addRow(new Object[]{ producto, "", "" });
        }}); 
    }

    private void calcularTotales() {
        DefaultTableModel modeloVentas = (DefaultTableModel) tblVentas.getModel();
        DefaultTableModel modeloPrecios = (DefaultTableModel) tblPrecios.getModel();
        DefaultTableModel modeloResultados = (DefaultTableModel) tblResultados.getModel();

        int idxProductoPre = -1;
        int idxCostoPre = -1;
        int idxPrecioPre = -1;
        for (int c = 0; c < modeloPrecios.getColumnCount(); c++) {
            String name = modeloPrecios.getColumnName(c).toLowerCase();
            if (name.contains("producto")) idxProductoPre = c;
            else if (name.contains("costo") || name.contains("compra")) idxCostoPre = c;
            else if (name.contains("precio") || name.contains("venta")) idxPrecioPre = c;
        }
        if (idxProductoPre == -1) idxProductoPre = 0;
        if (idxCostoPre == -1) idxCostoPre = 1;
        if (idxPrecioPre == -1) idxPrecioPre = 2;
    
        if (tblVentas.isEditing()) tblVentas.getCellEditor().stopCellEditing();
        if (tblPrecios.isEditing()) tblPrecios.getCellEditor().stopCellEditing();

        modeloResultados.setRowCount(0); // limpiar la tabla cuando ya no se ocupe

    for (int i = 0; i < modeloVentas.getRowCount(); i++) {
        Object prodObj = modeloVentas.getValueAt(i, 0);
        if (prodObj == null) continue;
        String producto = prodObj.toString().trim();
        if (producto.isEmpty()) continue;

        //revisa que coincida las cantidades
        boolean encontrado = false;
        double costo = 0;
        double precioVenta = 0;
        for (int j = 0; j < modeloPrecios.getRowCount(); j++) {
            Object pObj = modeloPrecios.getValueAt(j, idxProductoPre);
            if (pObj == null) continue;
            String prodPrecio = pObj.toString().trim();
            if (producto.equalsIgnoreCase(prodPrecio)) {
                // deja que ponga las comas como valor
                try {
                    Object costoObj = modeloPrecios.getValueAt(j, idxCostoPre);
                    String sCosto = costoObj == null ? "0" : costoObj.toString().trim().replace(",", ".");
                    costo = sCosto.isEmpty() ? 0 : Double.parseDouble(sCosto);
                } catch (Exception ex) {
                    costo = 0;
                }
                try {
                    Object precioObj = modeloPrecios.getValueAt(j, idxPrecioPre);
                    String sPrecio = precioObj == null ? "0" : precioObj.toString().trim().replace(",", ".");
                    precioVenta = sPrecio.isEmpty() ? 0 : Double.parseDouble(sPrecio);
                } catch (Exception ex) {
                    precioVenta = 0;
                }
                encontrado = true;
                break;
            }
        }

        if (!encontrado) {
           //pone ceros si no hay nada que se ingresara
            modeloResultados.addRow(new Object[]{ producto, 0.0, 0.0 });
            continue;
        }

        // Suma todos los valores de la semana
        double totalVendido = 0;
        for (int col = 1; col <= 7 && col < modeloVentas.getColumnCount(); col++) {
            Object val = modeloVentas.getValueAt(i, col);
            if (val == null) continue;
            String s = val.toString().trim();
            if (s.isEmpty()) continue;
            s = s.replace(",", "."); // si ingreso un numero decimal pero pongo coma en vez de punto es valido
            try {
                totalVendido += Double.parseDouble(s);
            } catch (NumberFormatException ex) {
                // no le hace caso si se intenta introducir texto en vez de numero osea cantidad
            }
        }
       
        double ingresoTotal = precioVenta * totalVendido;
        double utilidadTotal = (precioVenta - costo) * totalVendido;
        
        // solo deja dos decimales en vez de mas
        ingresoTotal = Math.round(ingresoTotal * 100.0) / 100.0;
        utilidadTotal = Math.round(utilidadTotal * 100.0) / 100.0;

        modeloResultados.addRow(new Object[]{ producto, ingresoTotal, utilidadTotal });
        }
    }
