    private void btnAbrirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirActionPerformed
        // TODO add your handling code here:
        try {
    JFileChooser fc = new JFileChooser();
    fc.setDialogTitle("Abrir archivo");

    if (fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
        java.io.File f = fc.getSelectedFile();
        java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(f));

        // Limpiar filas de las tablas
        ((DefaultTableModel) tblVentas.getModel()).setRowCount(0);
        ((DefaultTableModel) tblPrecios.getModel()).setRowCount(0);
        ((DefaultTableModel) tblResultados.getModel()).setRowCount(0);

        JTable tablaActual = null;
        DefaultTableModel modeloActual = null;
        boolean primeraLinea = false;
        String line;

        while ((line = br.readLine()) != null) {
            line = line.trim();
            if (line.isEmpty()) continue;

            if (line.startsWith("Tabla:")) {
                String nombre = line.substring(6);
                switch (nombre) {
                    case "Ventas": tablaActual = tblVentas; break;
                    case "Precios": tablaActual = tblPrecios; break;
                    case "Resultados": tablaActual = tblResultados; break;
                }
                modeloActual = (DefaultTableModel) tablaActual.getModel();
                primeraLinea = true;
            } else if (primeraLinea) {
                // Si la tabla ya tiene columnas no se agrega otra vez
                if (modeloActual.getColumnCount() == 0) {
                    String[] encabezados = line.split(",");
                    for (String e : encabezados) modeloActual.addColumn(e);
                }
                primeraLinea = false;
            } else {
                String[] datos = line.split(",");
                modeloActual.addRow(datos);
            }
        }
        br.close();
        JOptionPane.showMessageDialog(this, "Archivo cargado correctamente.");
    }
    } catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error al abrir archivo.");
    e.printStackTrace();
    }
    }//GEN-LAST:event_btnAbrirActionPerformed

