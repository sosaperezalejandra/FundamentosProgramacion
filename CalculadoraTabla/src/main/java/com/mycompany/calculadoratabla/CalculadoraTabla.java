    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        try {
            //selecciona ubicacion el JFilechooser
            JFileChooser fc = new JFileChooser();
            fc.setDialogTitle("Guardar la informacion de las tablas");

            if (fc.showSaveDialog(this) == JFileChooser.APPROVE_OPTION) {
            java.io.File f = fc.getSelectedFile();

            // Si no tiene extensión, agregamos .csv
            if (!f.getName().toLowerCase().endsWith(".csv")) {
            f = new java.io.File(f.getAbsolutePath() + ".csv");
        }
        //guarda toda la infromacion
        try (java.io.PrintWriter pw = new java.io.PrintWriter(f)) {

            JTable[] tablas = {tblVentas, tblPrecios, tblResultados};
            String[] nombres = {"Ventas", "Precios", "Resultados"};

            for (int t = 0; t < tablas.length; t++) {
                DefaultTableModel m = (DefaultTableModel) tablas[t].getModel();

                pw.println("Tabla:" + nombres[t]);

                // Encabezados
                for (int c = 0; c < m.getColumnCount(); c++) {
                    pw.print(m.getColumnName(c));
                    if (c < m.getColumnCount() - 1) pw.print(",");
                }
                pw.println();

                // Datos
                for (int i = 0; i < m.getRowCount(); i++) {
                    for (int c = 0; c < m.getColumnCount(); c++) {
                        Object valor = m.getValueAt(i, c);
                        pw.print(valor != null ? valor.toString() : "");
                        if (c < m.getColumnCount() - 1) pw.print(",");
                    }
                    pw.println();
                }
                pw.println();
            }
        }
        JOptionPane.showMessageDialog(this, "Archivo guardado correctamente en:\n" + f.getAbsolutePath());
        }
        }catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al guardar archivo.");
        e.printStackTrace();
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

